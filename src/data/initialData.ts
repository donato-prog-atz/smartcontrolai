// Helper to generate 24h realistic curves
const generateHourly = (baseWatts: number, activeHoursRange: [number, number], rate: number) => {
  const hours = [
    '00:00', '01:00', '02:00', '03:00', '04:00', '05:00',
    '06:00', '07:00', '08:00', '09:00', '10:00', '11:00',
    '12:00', '13:00', '14:00', '15:00', '16:00', '17:00',
    '18:00', '19:00', '20:00', '21:00', '22:00', '23:00',
  ];
  return hours.map((hour, idx) => {
    const isPeak = idx >= 18 && idx <= 21;
    const isActive = idx >= activeHoursRange[0] && idx <= activeHoursRange[1];
    const power = isActive ? baseWatts * (0.85 + Math.random() * 0.3) : baseWatts * 0.05;
    const kwh = parseFloat((power / 1000).toFixed(3));
    const effectiveRate = isPeak ? rate * 1.45 : rate;
    const cost = parseFloat((kwh * effectiveRate).toFixed(2));
    return { hour, kwh, cost, isPeak };
  });
};

const generateDaily = (avgDailyKwh: number, rate: number) => {
  const days = [
    { date: '10/10', dayName: 'Seg' },
    { date: '11/10', dayName: 'Ter' },
    { date: '12/10', dayName: 'Qua' },
    { date: '13/10', dayName: 'Qui' },
    { date: '14/10', dayName: 'Sex' },
    { date: '15/10', dayName: 'Sáb' },
    { date: '16/10', dayName: 'Hoje' },
  ];
  return days.map(d => {
    const variance = 0.8 + Math.random() * 0.4;
    const kwh = parseFloat((avgDailyKwh * variance).toFixed(2));
    const cost = parseFloat((kwh * rate).toFixed(2));
    return { ...d, kwh, cost };
  });
};

const generateMonthly = (avgMonthlyKwh: number, rate: number) => {
  const months = ['Nov', 'Dez', 'Jan', 'Fev', 'Mar', 'Abr', 'Mai', 'Jun', 'Jul', 'Ago', 'Set', 'Out'];
  return months.map(month => {
    const variance = 0.85 + Math.random() * 0.35;
    const kwh = parseFloat((avgMonthlyKwh * variance).toFixed(1));
    const cost = parseFloat((kwh * rate).toFixed(2));
    return { month, kwh, cost };
  });
};

